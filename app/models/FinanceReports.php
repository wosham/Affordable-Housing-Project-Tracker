class FinanceReports
{
    public const TYPES = ['payment_register', 'budget_summary', 'retention_report', 'ld_report', 'approved_unpaid', 'monthly_summary'];
    public const FORMATS = ['html', 'csv', 'json'];

    public static function cleanInput(array $input): array
    {
        $type = Security::cleanString((string)($input['type'] ?? 'monthly_summary'));
        $format = Security::cleanString((string)($input['format'] ?? 'html'));
        $filters = FinanceBudget::filters($input);

        return [
            'type' => in_array($type, self::TYPES, true) ? $type : 'monthly_summary',
            'format' => in_array($format, self::FORMATS, true) ? $format : 'html',
            'filters' => $filters,
            'auto_print' => !empty($input['print']) || !empty($input['auto_print']),
        ];
    }

    /**
     * Human labels for report type dropdowns.
     *
     * @return array<string, string>
     */
    public static function typeLabels(): array
    {
        $labels = [];
        foreach (self::TYPES as $type) {
            $labels[$type] = self::title($type);
        }
        return $labels;
    }

    /**
