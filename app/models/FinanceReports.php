    public static function generate(string $type, array $filters = []): array
    {
        $type = in_array($type, self::TYPES, true) ? $type : 'monthly_summary';
        $queryFilters = self::mapFiltersForType($type, $filters);
        $title = self::title($type);
        $rows = match ($type) {
            'payment_register' => self::payments($queryFilters),
            'budget_summary' => FinanceBudget::projectRows($queryFilters, 500),
            'retention_report' => FinanceBudget::retentionRows($queryFilters, 500),
            'ld_report' => FinanceBudget::liquidatedDamageRows($queryFilters, 500),
            'approved_unpaid' => FinancePayment::approvedList($queryFilters, 500, 0),
            default => self::monthlySummary($queryFilters),
        };

        $summary = self::summary($type, $rows);

        return [
            'title' => $title,
            'type' => $type,
            'type_label' => $title,
            'org' => self::orgName(),
            'programme' => 'Trans-Nzoia Affordable Housing Programme',
            'generated_by' => Auth::name() ?: 'Finance',
            'generated_at' => date('Y-m-d H:i:s'),
            'generated_at_label' => format_datetime(date('Y-m-d H:i:s')),
            'filters' => $filters,
            'filter_labels' => self::filterLabels($filters),
            'filter_support' => self::filterSupport($type),
            'summary' => $summary,
            'summary_cards' => self::summaryCards($type, $rows, $summary),
            'columns' => self::columns($type),
            'rows' => $rows,
            'row_count' => count($rows),
        ];
    }

    public static function csv(array $report): string
    {
        $handle = fopen('php://temp', 'r+');
        fputcsv($handle, [$report['org'] ?? self::orgName()]);
        fputcsv($handle, [$report['title'] ?? 'Finance report']);
        fputcsv($handle, ['Generated by', $report['generated_by'] ?? '']);
        fputcsv($handle, ['Generated at', $report['generated_at'] ?? '']);
        foreach (($report['filter_labels'] ?? []) as $label => $value) {
            fputcsv($handle, [$label, $value]);
        }
        fputcsv($handle, []);
        $columns = $report['columns'] ?? [];
        fputcsv($handle, array_values($columns));
        foreach (($report['rows'] ?? []) as $row) {
            fputcsv($handle, array_map(static fn ($key) => self::cell($row, (string)$key), array_keys($columns)));
        }
        rewind($handle);
        return stream_get_contents($handle) ?: '';
    }

    /**
