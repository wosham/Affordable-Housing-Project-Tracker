        $html .= '<strong>Finance Report</strong>';
        $html .= '<span>Generated ' . Security::e($generatedAt) . '</span>';
        $html .= '<span>By ' . Security::e($generatedBy) . '</span>';
        $html .= '</div></header>';

        $html .= '<section class="sheet__title">';
        $html .= '<h1>' . Security::e($title) . '</h1>';
        $html .= '<p>' . Security::e((string)$rowCount) . ' record' . ($rowCount === 1 ? '' : 's') . ' · Official finance print view</p>';
        $html .= '</section>';

        if ($filterLabels !== []) {
            $html .= '<section class="sheet__filters"><h2>Applied filters</h2><ul>';
            foreach ($filterLabels as $label => $value) {
                $html .= '<li><span>' . Security::e((string)$label) . '</span><strong>' . Security::e((string)$value) . '</strong></li>';
            }
            $html .= '</ul></section>';
        }

        if ($cards !== []) {
            $html .= '<section class="sheet__cards">';
            foreach ($cards as $card) {
                $html .= '<article><em>' . Security::e((string)($card['label'] ?? '')) . '</em><strong>' . Security::e((string)($card['value'] ?? '')) . '</strong></article>';
            }
