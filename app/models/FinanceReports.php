    private static function summary(string $type, array $rows): array
    {
        $base = ['rows' => count($rows), 'type' => self::title($type)];

        return match ($type) {
            'payment_register' => $base + [
                'total_paid' => array_sum(array_map(static fn ($r) => (float)($r['amount'] ?? 0), $rows)),
            ],
            'budget_summary' => $base + [
                'contract_value' => array_sum(array_map(static fn ($r) => (float)($r['contract_sum'] ?? 0), $rows)),
                'paid_value' => array_sum(array_map(static fn ($r) => (float)($r['paid_amount'] ?? 0), $rows)),
                'approved_unpaid' => array_sum(array_map(static fn ($r) => (float)($r['approved_unpaid'] ?? 0), $rows)),
            ],
            'retention_report' => $base + [
                'held' => array_sum(array_map(static fn ($r) => (float)($r['total_held'] ?? 0), $rows)),
                'balance' => array_sum(array_map(static fn ($r) => (float)($r['balance_amount'] ?? 0), $rows)),
            ],
            'ld_report' => $base + [
                'total_ld' => array_sum(array_map(static fn ($r) => (float)($r['total_ld'] ?? 0), $rows)),
            ],
            'approved_unpaid' => $base + [
                'net_payable' => array_sum(array_map(static fn ($r) => (float)($r['outstanding_amount'] ?? 0), $rows)),
            ],
            default => $base + [
                'paid_value' => array_sum(array_map(static fn ($r) => (float)($r['paid_amount'] ?? 0), $rows)),
                'payment_count' => array_sum(array_map(static fn ($r) => (int)($r['payment_count'] ?? 0), $rows)),
            ],
        };
    }

