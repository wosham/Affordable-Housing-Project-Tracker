    /**
     * @return array<string, string>
     */
    private static function filterLabels(array $filters): array
    {
        $labels = [];
        if (!empty($filters['project_id'])) {
            $project = Database::fetch('SELECT name FROM projects WHERE id = ? LIMIT 1', [(int)$filters['project_id']]);
            $labels['Project'] = (string)($project['name'] ?? ('#' . (int)$filters['project_id']));
        }
        if (!empty($filters['q'])) {
            $labels['Search'] = (string)$filters['q'];
        }
        if (!empty($filters['date_from'])) {
            $labels['From'] = format_date((string)$filters['date_from']);
        }
        if (!empty($filters['date_to'])) {
            $labels['To'] = format_date((string)$filters['date_to']);
        }
        if (!empty($filters['status'])) {
            $labels['Status'] = status_label((string)$filters['status']);
        }
        if (!empty($filters['risk'])) {
            $labels['Signal'] = status_label((string)$filters['risk']);
        }
        return $labels;
    }

    private static function orgName(): string
    {
        try {
            if (class_exists('SystemConfig')) {
                $name = trim((string)(SystemConfig::get('app_name') ?? SystemConfig::get('site_name') ?? ''));
                if ($name !== '') {
                    return $name;
                }
            }
        } catch (Throwable) {
        }

        return 'County Government of Trans-Nzoia';
    }

    private static function isMoneyKey(string $key): bool
    {
        return (bool)preg_match('/(amount|value|sum|held|released|balance|rate|ld|retention|gross|net|paid|unpaid)/i', $key);
    }

    public static function cell(array $row, string $key): string
    {
        $value = $row[$key] ?? '';

        if ($key === 'status' || $key === 'risk_label') {
            if ($key === 'risk_label') {
                return (string)$value;
            }
            return status_label((string)$value);
        }

        if ($key === 'payment_count' || $key === 'days_overdue') {
            return format_number((float)$value);
        }

        if (is_numeric($value) && self::isMoneyKey($key)) {
            return format_money((float)$value);
        }

        if (str_ends_with($key, '_at') || str_ends_with($key, '_date')) {
            return format_date($value !== '' && $value !== null ? (string)$value : null);
        }

        if ($key === 'ipc_number' && $value !== '' && $value !== null) {
            return 'IPC #' . $value;
        }

        if ($key === 'month_label' && is_string($value) && preg_match('/^\d{4}-\d{2}$/', $value)) {
            $ts = strtotime($value . '-01');
            return $ts ? date('M Y', $ts) : $value;
        }

        return (string)$value;
    }

