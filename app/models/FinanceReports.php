        $html .= '<button type="button" onclick="window.close()">Close</button>';
        $html .= '</div>';

        $html .= '<table class="sheet__table"><thead><tr>';
        foreach ($columns as $key => $label) {
            $class = self::isMoneyKey((string)$key) ? ' class="money"' : '';
            $html .= '<th' . $class . '>' . Security::e((string)$label) . '</th>';
        }
        $html .= '</tr></thead><tbody>';

        if (($report['rows'] ?? []) === []) {
            $html .= '<tr><td colspan="' . max(1, count($columns)) . '" class="empty">No records found for the selected filters.</td></tr>';
        } else {
            foreach ($report['rows'] as $row) {
                $html .= '<tr>';
                foreach (array_keys($columns) as $key) {
                    $class = self::isMoneyKey((string)$key) ? ' class="money"' : '';
                    $html .= '<td' . $class . '>' . Security::e(self::cell($row, (string)$key)) . '</td>';
                }
                $html .= '</tr>';
            }
        }

        $html .= '</tbody></table>';

        $html .= '<footer class="sheet__footer">';
        $html .= '<p>Confidential — for authorised County / programme finance use only.</p>';
        $html .= '<p>' . Security::e($org) . ' · ' . Security::e($title) . ' · Page printed from the finance portal</p>';
        $html .= '</footer></div>';

        if ($autoPrint) {
            $html .= '<script>window.addEventListener("load",function(){setTimeout(function(){window.print();},250);});</script>';
        }

        $html .= '</body></html>';
        return $html;
    }

    public static function recordRun(int $userId, string $type, string $format, array $filters, int $rowCount, string $status = 'generated'): void
    {
        try {
            Database::query(
                'INSERT INTO report_runs (user_id, report_type, format, filters_json, row_count, status, created_at)
                 VALUES (?, ?, ?, ?, ?, ?, NOW())',
                [$userId, 'finance_' . $type, $format, json_encode($filters, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE), $rowCount, $status]
            );
        } catch (Throwable) {
        }
    }

    public static function recentRuns(int $limit = 8): array
    {
        $rows = Database::fetchAll(
            "SELECT rr.*, CONCAT(u.first_name, ' ', u.last_name) AS user_name
             FROM report_runs rr
             LEFT JOIN users u ON u.id = rr.user_id
             WHERE rr.report_type LIKE 'finance_%'
             ORDER BY rr.created_at DESC
             LIMIT " . max(1, $limit)
        );

        return array_map(static function (array $row): array {
            $type = (string)preg_replace('/^finance_/', '', (string)($row['report_type'] ?? ''));
            $row['type_key'] = $type;
            $row['type_label'] = self::title($type !== '' ? $type : 'monthly_summary');
            $row['format_label'] = match (strtolower((string)($row['format'] ?? ''))) {
                'csv' => 'CSV export',
                'json' => 'JSON',
                'html', 'print' => 'Print view',
                'preview' => 'On-screen preview',
                default => strtoupper((string)($row['format'] ?? 'report')),
            };
            return $row;
        }, $rows);
    }

    /**
     * Map UI filters to each report consumer's expected keys.
     */
    private static function mapFiltersForType(string $type, array $filters): array
    {
        $mapped = $filters;

        if ($type === 'approved_unpaid') {
            if (!empty($filters['date_from']) && empty($filters['approved_from'])) {
                $mapped['approved_from'] = $filters['date_from'];
            }
            if (!empty($filters['date_to']) && empty($filters['approved_to'])) {
                $mapped['approved_to'] = $filters['date_to'];
            }
        }

        // Budget is a live snapshot — strip date keys so callers stay honest.
        if ($type === 'budget_summary') {
            unset($mapped['date_from'], $mapped['date_to'], $mapped['approved_from'], $mapped['approved_to']);
        }

        return $mapped;
    }

    private static function payments(array $filters): array
    {
        $where = ["pay.status = 'processed'"];
        $bindings = [];
        if (!empty($filters['project_id'])) {
            $where[] = 'p.id = ?';
            $bindings[] = (int)$filters['project_id'];
        }
        foreach (['date_from' => '>=', 'date_to' => '<='] as $key => $op) {
            $date = trim((string)($filters[$key] ?? ''));
            if (preg_match('/^\d{4}-\d{2}-\d{2}$/', $date)) {
                $where[] = "pay.payment_date {$op} ?";
                $bindings[] = $date;
            }
        }
        $q = trim((string)($filters['q'] ?? ''));
        if ($q !== '') {
            $where[] = '(p.name LIKE ? OR pay.reference_no LIKE ? OR contractor.first_name LIKE ? OR contractor.last_name LIKE ?)';
            $term = '%' . $q . '%';
            array_push($bindings, $term, $term, $term, $term);
        }

        return Database::fetchAll(
            "SELECT pay.*, i.ipc_number, p.name AS project_name,
                    CONCAT(contractor.first_name, ' ', contractor.last_name) AS contractor_name,
                    CONCAT(processor.first_name, ' ', processor.last_name) AS processed_by_name
             FROM payments pay
             JOIN ipcs i ON i.id = pay.ipc_id
             JOIN projects p ON p.id = pay.project_id
             JOIN users contractor ON contractor.id = i.contractor_id
             JOIN users processor ON processor.id = pay.processed_by
             WHERE " . implode(' AND ', $where) . "
             ORDER BY pay.payment_date DESC, pay.id DESC
             LIMIT 500",
            $bindings
        );
    }

    private static function monthlySummary(array $filters): array
    {
        $where = ["pay.status = 'processed'"];
        $bindings = [];

        if (!empty($filters['project_id'])) {
            $where[] = 'p.id = ?';
            $bindings[] = (int)$filters['project_id'];
        }
        foreach (['date_from' => '>=', 'date_to' => '<='] as $key => $op) {
            $date = trim((string)($filters[$key] ?? ''));
            if (preg_match('/^\d{4}-\d{2}-\d{2}$/', $date)) {
                $where[] = "pay.payment_date {$op} ?";
                $bindings[] = $date;
            }
        }
        $q = trim((string)($filters['q'] ?? ''));
        if ($q !== '') {
            $where[] = '(p.name LIKE ? OR pay.reference_no LIKE ?)';
            $term = '%' . $q . '%';
            array_push($bindings, $term, $term);
        }

        return Database::fetchAll(
            "SELECT DATE_FORMAT(pay.payment_date, '%Y-%m') AS month_label,
                    COUNT(*) AS payment_count,
                    COALESCE(SUM(pay.amount), 0) AS paid_amount,
                    COALESCE(SUM(i.retention_amount), 0) AS retention_amount
             FROM payments pay
             JOIN ipcs i ON i.id = pay.ipc_id
             JOIN projects p ON p.id = pay.project_id
             WHERE " . implode(' AND ', $where) . "
             GROUP BY DATE_FORMAT(pay.payment_date, '%Y-%m')
             ORDER BY month_label DESC
             LIMIT 24",
            $bindings
        );
    }

