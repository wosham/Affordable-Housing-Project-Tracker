              <p>The Maili Tatu Estate project, which forms the centrepiece of Kitale Central Constituency&rsquo;s AHP allocation, comprises a total of 600 units across three phases. Phases 2 and 3 &mdash; covering the remaining 400 units &mdash; are currently under active construction, with completion projected for Q1 2027. The project was awarded to Ramco Builders Ltd under a competitive tender process, and has been monitored through the county&rsquo;s integrated AHP project tracker.</p>

