              <p>The Trans-Nzoia County Affordable Housing Programme reached a defining milestone on 15 May 2026 when Governor George Natembeya formally handed over the keys to 200 completed housing units at the Maili Tatu Estate in Kitale. The ceremony, attended by Cabinet Secretary for Housing Charles Hinga, Members of the County Assembly, and hundreds of jubilant beneficiaries, marked the first mass delivery of finished units under the programme since its inception in 2023.</p>

              <p>The units &mdash; a mix of one-bedroom and two-bedroom typologies spread across Blocks A to E of the estate &mdash; were delivered ahead of the original June 2026 schedule, a development the Governor attributed to strict contractor supervision and the county&rsquo;s commitment to accountability in public procurement. Each unit was allocated to vetted beneficiaries drawn from the county&rsquo;s housing waitlist, following a transparent selection process overseen by the National Housing Corporation (NHC) and county housing officials.</p>

              <div class="article-pullquote" role="blockquote">
