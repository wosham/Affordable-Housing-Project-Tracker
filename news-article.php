              <h2>About the Maili Tatu Estate Project</h2>

              <p>Situated on a 12-acre parcel of public land approximately 3 kilometres from Kitale town centre, the Maili Tatu Estate was designed by Nairobi-based architects Mungai &amp; Associates to deliver high-density, medium-rise residential units that maximise land use while providing adequate amenity space. Each block is four storeys high, with shared stairwells, ground-floor parking bays, and a communal courtyard at its centre.</p>

