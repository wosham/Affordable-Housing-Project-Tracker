              <p>Cabinet Secretary Charles Hinga, speaking at the ceremony, commended Trans-Nzoia County for being among the first counties under the national AHP framework to achieve a Phase 1 handover, and called on other counties to replicate the model. He also announced that an additional KSh 450 million had been allocated to Trans-Nzoia County under the Supplementary Budget to accelerate Phase 2 construction at Maili Tatu and fund groundbreaking at two new sites in Endebess and Saboti constituencies.</p>

