              <h2>Beneficiary Selection Process</h2>

              <p>The selection of Phase 1 beneficiaries was conducted over a three-month period between February and April 2026, involving joint teams from the NHC, the Trans-Nzoia County Department of Land, Housing &amp; Physical Planning, and independent civil society observers. Applicants were ranked based on income verification, residency duration in Trans-Nzoia County, vulnerability status, and existing housing conditions. Priority was given to civil servants earning below KSh 30,000 per month, single-parent households, persons with disabilities, and informal sector workers registered with the Kenya Revenue Authority (KRA).</p>

              <p>A total of 4,812 applications were received for the 200 Phase 1 units, representing an oversubscription ratio of approximately 24:1. Unsuccessful applicants have been placed on a county waitlist and will be given first consideration when Phase 2 and Phase 3 units become available. The county has committed to publishing the full beneficiary list on the AHP Tracker portal within 14 days of the handover ceremony in the interest of transparency and public accountability.</p>

